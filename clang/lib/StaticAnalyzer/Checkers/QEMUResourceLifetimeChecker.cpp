static SymbolRef canonicalRefSymbol(ProgramStateRef State, SymbolRef Sym) {
  for (unsigned I = 0; Sym && I != 16; ++I) {
    const SymbolRef *Parent = State->get<QEMURefAliases>(Sym);
    if (!Parent || *Parent == Sym)
      break;
    Sym = *Parent;
  }
  return Sym;
}

static const VarRegion *findLocalBinding(const Stmt *S, SymbolRef Sym,
                                         ProgramStateRef State,
                                         CheckerContext &C) {
  if (!S || !Sym)
    return nullptr;
  if (const auto *DRE = dyn_cast<DeclRefExpr>(S)) {
    const auto *VD = dyn_cast<VarDecl>(DRE->getDecl());
    if (VD) {
      const VarRegion *VR = State->getRegion(VD, C.getStackFrame());
      if (VR->hasMemorySpace<StackSpaceRegion>(State)) {
        SymbolRef ValueSym = State->getSVal(VR).getAsSymbol();
        if (canonicalRefSymbol(State, ValueSym) == Sym)
          return VR;
      }
    }
  }
  for (const Stmt *Child : S->children())
    if (const VarRegion *VR = findLocalBinding(Child, Sym, State, C))
      return VR;
  return nullptr;
}

static const VarRegion *findDirectLocalBinding(const Expr *E,
                                               ProgramStateRef State,
                                               CheckerContext &C) {
  if (!E)
    return nullptr;
  const auto *DRE = dyn_cast<DeclRefExpr>(E->IgnoreParenImpCasts());
  const auto *VD = DRE ? dyn_cast<VarDecl>(DRE->getDecl()) : nullptr;
  if (!VD)
    return nullptr;
  const VarRegion *VR = State->getRegion(VD, C.getStackFrame());
  return VR->hasMemorySpace<StackSpaceRegion>(State) ? VR : nullptr;
}

static bool isQEMUQueueMacro(const Expr *E, CheckerContext &C) {
  if (!E)
    return false;
  SourceLocation Loc = E->getExprLoc();
  const SourceManager &SM = C.getSourceManager();
  while (Loc.isMacroID()) {
    StringRef Name =
        Lexer::getImmediateMacroName(Loc, SM, C.getASTContext().getLangOpts());
    if (Name.starts_with("QLIST_") || Name.starts_with("QTAILQ_") ||
        Name.starts_with("QSLIST_") || Name.starts_with("QSIMPLEQ_"))
      return true;
    Loc = SM.getImmediateMacroCallerLoc(Loc);
  }
  return false;
}

static bool isQEMUQueueRemovalMacro(const Expr *E, CheckerContext &C) {
  if (!E)
    return false;
  SourceLocation Loc = E->getExprLoc();
  const SourceManager &SM = C.getSourceManager();
  while (Loc.isMacroID()) {
    StringRef Name =
        Lexer::getImmediateMacroName(Loc, SM, C.getASTContext().getLangOpts());
    if (Name == "QLIST_REMOVE" || Name == "QLIST_SAFE_REMOVE" ||
        Name == "QTAILQ_REMOVE" || Name == "QSLIST_REMOVE")
      return true;
    Loc = SM.getImmediateMacroCallerLoc(Loc);
  }
  return false;
}

static bool isQEMUQueueHeadMacro(const Expr *E, CheckerContext &C) {
  if (!E)
    return false;
  SourceLocation Loc = E->getExprLoc();
  const SourceManager &SM = C.getSourceManager();
  while (Loc.isMacroID()) {
    StringRef Name =
        Lexer::getImmediateMacroName(Loc, SM, C.getASTContext().getLangOpts());
    if (Name == "QLIST_FIRST" || Name == "QTAILQ_FIRST" ||
        Name == "QSLIST_FIRST" || Name == "QSIMPLEQ_FIRST")
      return true;
    Loc = SM.getImmediateMacroCallerLoc(Loc);
  }
  return false;
}

static bool referencesLocalBinding(const Stmt *S, const MemRegion *Binding,
                                   ProgramStateRef State, CheckerContext &C) {
  if (!S || !Binding)
    return false;
  if (const auto *DRE = dyn_cast<DeclRefExpr>(S)) {
    const auto *VD = dyn_cast<VarDecl>(DRE->getDecl());
    if (VD && State->getRegion(VD, C.getStackFrame()) == Binding)
      return true;
  }
  for (const Stmt *Child : S->children())
    if (referencesLocalBinding(Child, Binding, State, C))
      return true;
  return false;
}

static const Stmt *getLoopBody(const Stmt *S) {
  if (const auto *Loop = dyn_cast<ForStmt>(S))
    return Loop->getBody();
  if (const auto *Loop = dyn_cast<WhileStmt>(S))
    return Loop->getBody();
  if (const auto *Loop = dyn_cast<DoStmt>(S))
    return Loop->getBody();
  if (const auto *Loop = dyn_cast<CXXForRangeStmt>(S))
    return Loop->getBody();
  return nullptr;
}

static const Stmt *findEnclosingBodyLoop(DynTypedNode Node, ASTContext &Ctx) {
  const Stmt *Child = Node.get<Stmt>();
  for (;;) {
    DynTypedNodeList Parents = Ctx.getParents(Node);
    if (Parents.size() != 1)
      return nullptr;
    Node = Parents[0];
    const Stmt *Parent = Node.get<Stmt>();
    if (!Parent)
      return nullptr;
    if (const Stmt *Body = getLoopBody(Parent))
      return Body == Child ? Parent : nullptr;
    Child = Parent;
  }
}

class QEMUResourceLifetimeChecker
    : public Checker<check::PreCall, check::PostCall, check::Location,
                     check::Bind, check::DeadSymbols> {
  const BugType PointerBug{this, "Invalid QEMU-managed pointer lifetime",
                           "QEMU resource lifetime"};
  const BugType ReferenceBug{this, "Invalid QEMU reference lifetime",
                             "QEMU resource lifetime"};
  const BugType DescriptorBug{this, "Invalid QEMU descriptor lifetime",
                              "QEMU resource lifetime"};

  static SymbolRef canonicalRef(ProgramStateRef State, SymbolRef Sym) {
    return canonicalRefSymbol(State, Sym);
  }

  static bool isReboundThrough(const MemRegion *Binding, const Expr *At,
                               SymbolRef Sym, ProgramStateRef State,
                               CheckerContext &C) {
    if (!Binding || !State->contains<QEMUReboundBindings>(Binding))
      return false;
    const VarRegion *UseBinding = findLocalBinding(At, Sym, State, C);
    return UseBinding == Binding || (!UseBinding && isQEMUQueueMacro(At, C));
  }

  static bool isLoopCarriedQueueRemoval(const MemRegion *Binding,
                                        const Expr *At, const Expr *Origin,
                                        ProgramStateRef State,
                                        CheckerContext &C) {
    if (!Binding || !At || !Origin || !isQEMUQueueRemovalMacro(At, C))
      return false;

    const auto *UseBinding = dyn_cast<VarRegion>(Binding);
    if (!UseBinding || !referencesLocalBinding(At, Binding, State, C))
      return false;
    const auto *VD = dyn_cast<VarDecl>(UseBinding->getDecl());
    if (!VD || !isQEMUQueueHeadMacro(VD->getInit(), C))
      return false;

    ASTContext &Ctx = C.getASTContext();
    const Stmt *UseLoop = findEnclosingBodyLoop(DynTypedNode::create(*At), Ctx);
    const Stmt *DeclLoop =
        findEnclosingBodyLoop(DynTypedNode::create(*VD), Ctx);
    if (!UseLoop || UseLoop != DeclLoop)
      return false;

    const SourceManager &SM = C.getSourceManager();
    SourceLocation UseLoc = SM.getExpansionLoc(At->getExprLoc());
    SourceLocation ReleaseLoc = SM.getExpansionLoc(Origin->getExprLoc());
    if (UseLoc.isInvalid() || ReleaseLoc.isInvalid() ||
        SM.getFileID(UseLoc) != SM.getFileID(ReleaseLoc))
      return false;

    // When a removal appears textually before its release, the only path on
    // which the release can precede the removal is a loop backedge.  QEMU's
    // intrusive queue contract makes the element selected on the next
    // iteration a new logical object even when the core analyzer reuses the
    // old symbolic value for the list head.
    return SM.isBeforeInTranslationUnit(UseLoc, ReleaseLoc);
  }

  static const unsigned *getRefCount(ProgramStateRef State, RefKind Kind,
                                     SymbolRef Sym) {
    return Kind == RefKind::QOM ? State->get<QEMUQOMRefCounts>(Sym)
                                : State->get<QEMUQObjectRefCounts>(Sym);
  }

  static bool isReleasedRef(ProgramStateRef State, RefKind Kind,
                            SymbolRef Sym) {
    return Kind == RefKind::QOM ? State->contains<QEMUReleasedQOMRefs>(Sym)
                                : State->contains<QEMUReleasedQObjectRefs>(Sym);
  }

  static ProgramStateRef setRefCount(ProgramStateRef State, RefKind Kind,
                                     SymbolRef Sym, unsigned Count) {
    if (Count) {
      if (const MemRegion *const *Binding =
              State->get<QEMUReleasedRefBindings>(Sym))
        State = State->remove<QEMUReboundBindings>(*Binding);
      State = State->remove<QEMUReleasedRefOrigins>(Sym)
                  ->remove<QEMUReleasedRefBindings>(Sym);
    }
    if (Kind == RefKind::QOM) {
      State = Count ? State->set<QEMUQOMRefCounts>(Sym, Count)
                    : State->remove<QEMUQOMRefCounts>(Sym);
      State = Count ? State->remove<QEMUReleasedQOMRefs>(Sym)
                    : State->add<QEMUReleasedQOMRefs>(Sym);
    } else {
      State = Count ? State->set<QEMUQObjectRefCounts>(Sym, Count)
                    : State->remove<QEMUQObjectRefCounts>(Sym);
      State = Count ? State->remove<QEMUReleasedQObjectRefs>(Sym)
                    : State->add<QEMUReleasedQObjectRefs>(Sym);
    }
    return State;
  }

  static StringRef pointerReleaseName(unsigned Kind) {
    return Kind == static_cast<unsigned>(CallRole::QAPIFree) ? "QAPI free"
                                                             : "g_free";
  }

  void report(const BugType &Type, StringRef Message, SymbolRef Sym,
              const Expr *At, const Expr *Origin, StringRef OriginNote,
              ProgramStateRef State, CheckerContext &C) const {
    ExplodedNode *N = C.generateNonFatalErrorNode(State);
    if (!N)
      return;
    auto R = std::make_unique<PathSensitiveBugReport>(Type, Message, N);
    if (At)
      R->addRange(At->getSourceRange());
    if (Origin)
      R->addNote(OriginNote, {Origin, C.getSourceManager(), C.getStackFrame()});
    R->markInteresting(Sym);
    C.emitReport(std::move(R));
  }

  bool reportReleasedPointerUse(SymbolRef Sym, const Expr *At,
                                StringRef Description, ProgramStateRef State,
                                CheckerContext &C) const {
    const unsigned *Kind = State->get<QEMUReleasedPointers>(Sym);
    if (!Kind)
      return false;
    const MemRegion *Binding =
        State->get<QEMUReleasedPointerBindings>(Sym)
            ? *State->get<QEMUReleasedPointerBindings>(Sym)
            : nullptr;
    if (isReboundThrough(Binding, At, Sym, State, C))
      return false;
    const Expr *Origin = State->get<QEMUReleasedPointerOrigins>(Sym)
                             ? *State->get<QEMUReleasedPointerOrigins>(Sym)
                             : nullptr;
    std::string Message =
        (Description + " after it was released by " + pointerReleaseName(*Kind))
            .str();
    report(PointerBug, Message, Sym, At, Origin, "Pointer released here", State,
           C);
    return true;
  }

  void handlePointerRelease(const CallEvent &Call, ClassifiedCall Classified,
                            CheckerContext &C) const;
  void handleRefChange(const CallEvent &Call, RefKind Kind, bool Acquire,
                       bool Indirect, CheckerContext &C) const;
  void handleFDClose(const CallEvent &Call, CheckerContext &C) const;
  bool checkClosedFDUses(const CallEvent &Call, const FunctionDecl *FD,
                         CheckerContext &C) const;

public:
  void checkPreCall(const CallEvent &Call, CheckerContext &C) const;
  void checkPostCall(const CallEvent &Call, CheckerContext &C) const;
  void checkLocation(SVal Loc, bool IsLoad, const Stmt *S,
                     CheckerContext &C) const;
  void checkBind(SVal Loc, SVal Val, const Stmt *S, bool AtDeclInit,
                 CheckerContext &C) const;
  void checkDeadSymbols(SymbolReaper &SymReaper, CheckerContext &C) const;
};

void QEMUResourceLifetimeChecker::handlePointerRelease(
    const CallEvent &Call, ClassifiedCall Classified, CheckerContext &C) const {
  ProgramStateRef State = C.getState();
  SVal Value = releasedValue(Call, State, Classified.Indirect);
  SymbolRef Sym = Value.getAsSymbol();
  if (!Sym)
    return;

  const Expr *ValueExpr = Call.getNumArgs() ? Call.getArgExpr(0) : nullptr;
  const VarRegion *Binding = findLocalBinding(ValueExpr, Sym, State, C);
  if (!Binding)
    Binding = findDirectLocalBinding(ValueExpr, State, C);

  if (const unsigned *Previous = State->get<QEMUReleasedPointers>(Sym)) {
    const MemRegion *PreviousBinding =
        State->get<QEMUReleasedPointerBindings>(Sym)
            ? *State->get<QEMUReleasedPointerBindings>(Sym)
            : nullptr;
    if (isReboundThrough(PreviousBinding, ValueExpr, Sym, State, C)) {
      State = State
                  ->set<QEMUReleasedPointers>(
                      Sym, static_cast<unsigned>(Classified.Role))
                  ->set<QEMUReleasedPointerOrigins>(Sym, Call.getOriginExpr());
      if (Binding)
        State = State->set<QEMUReleasedPointerBindings>(Sym, Binding)
                    ->remove<QEMUReboundBindings>(Binding);
      else
        State = State->remove<QEMUReleasedPointerBindings>(Sym);
      C.addTransition(State);
      return;
    }
    const Expr *Origin = State->get<QEMUReleasedPointerOrigins>(Sym)
                             ? *State->get<QEMUReleasedPointerOrigins>(Sym)
                             : nullptr;
    std::string Message = ("Pointer released by " +
                           pointerReleaseName(*Previous) + " is released again")
                              .str();
    report(PointerBug, Message, Sym, Call.getOriginExpr(), Origin,
           "Pointer first released here", State, C);
    return;
  }

  auto [NonNull, Null] = assumeNonNull(State, Value);
  if (NonNull) {
    NonNull = NonNull
                  ->set<QEMUReleasedPointers>(
                      Sym, static_cast<unsigned>(Classified.Role))
                  ->set<QEMUReleasedPointerOrigins>(Sym, Call.getOriginExpr());
    if (Binding)
      NonNull = NonNull->set<QEMUReleasedPointerBindings>(Sym, Binding)
                    ->remove<QEMUReboundBindings>(Binding);
    C.addTransition(NonNull);
  }
  if (Null)
    C.addTransition(Null);
}

void QEMUResourceLifetimeChecker::handleRefChange(const CallEvent &Call,
                                                  RefKind Kind, bool Acquire,
                                                  bool Indirect,
                                                  CheckerContext &C) const {
  ProgramStateRef State = C.getState();
  SVal Value = releasedValue(Call, State, Indirect);
  SymbolRef Sym = Value.getAsSymbol();
  if (!Sym)
    return;
  Sym = canonicalRef(State, Sym);
  const Expr *ValueExpr = Call.getNumArgs() ? Call.getArgExpr(0) : nullptr;
  const VarRegion *Binding = findLocalBinding(ValueExpr, Sym, State, C);

  if (Acquire) {
    if (const unsigned *Count = getRefCount(State, Kind, Sym)) {
      unsigned NewCount = std::min(*Count + 1, 8u);
      C.addTransition(setRefCount(State, Kind, Sym, NewCount));
    }
    return;
  }

  if (isReleasedRef(State, Kind, Sym)) {
    const MemRegion *PreviousBinding =
        State->get<QEMUReleasedRefBindings>(Sym)
            ? *State->get<QEMUReleasedRefBindings>(Sym)
            : nullptr;
    if (isReboundThrough(PreviousBinding, ValueExpr, Sym, State, C)) {
      State = State->set<QEMUReleasedRefOrigins>(Sym, Call.getOriginExpr());
      if (Binding)
        State = State->set<QEMUReleasedRefBindings>(Sym, Binding)
                    ->remove<QEMUReboundBindings>(Binding);
      else
        State = State->remove<QEMUReleasedRefBindings>(Sym);
      C.addTransition(State);
      return;
    }
    const Expr *Origin = State->get<QEMUReleasedRefOrigins>(Sym)
                             ? *State->get<QEMUReleasedRefOrigins>(Sym)
                             : nullptr;
    StringRef Family = Kind == RefKind::QOM ? "QOM" : "QObject";
    report(ReferenceBug,
           ("Owned " + Family + " reference is released more than once").str(),
           Sym, Call.getOriginExpr(), Origin,
           "Owned reference first released here", State, C);
    return;
  }

  const unsigned *Count = getRefCount(State, Kind, Sym);
  if (!Count)
    return;

  auto [NonNull, Null] = assumeNonNull(State, Value);
  if (NonNull) {
    unsigned NewCount = *Count - 1;
    NonNull = setRefCount(NonNull, Kind, Sym, NewCount);
    if (!NewCount) {
      NonNull = NonNull->set<QEMUReleasedRefOrigins>(Sym, Call.getOriginExpr());
      if (Binding)
        NonNull = NonNull->set<QEMUReleasedRefBindings>(Sym, Binding)
                      ->remove<QEMUReboundBindings>(Binding);
    }
    C.addTransition(NonNull);
  }
  if (Null)
    C.addTransition(Null);
}

void QEMUResourceLifetimeChecker::handleFDClose(const CallEvent &Call,
                                                CheckerContext &C) const {
  if (!Call.getNumArgs())
    return;
  const Expr *Arg = Call.getArgExpr(0);
  if (Arg && C.isNegative(Arg))
    return;

  ProgramStateRef State = C.getState();
  SymbolRef Sym = Call.getArgSVal(0).getAsSymbol();
  if (!Sym)
    return;
  const VarRegion *Binding = findLocalBinding(Arg, Sym, State, C);
  if (State->contains<QEMUClosedFDs>(Sym)) {
    const MemRegion *PreviousBinding =
        State->get<QEMUClosedFDBindings>(Sym)
            ? *State->get<QEMUClosedFDBindings>(Sym)
            : nullptr;
    if (isReboundThrough(PreviousBinding, Arg, Sym, State, C)) {
      State = State->set<QEMUClosedFDOrigins>(Sym, Call.getOriginExpr());
      if (Binding)
        State = State->set<QEMUClosedFDBindings>(Sym, Binding)
                    ->remove<QEMUReboundBindings>(Binding);
      else
        State = State->remove<QEMUClosedFDBindings>(Sym);
      C.addTransition(State);
      return;
    }
    const Expr *Origin = State->get<QEMUClosedFDOrigins>(Sym)
                             ? *State->get<QEMUClosedFDOrigins>(Sym)
                             : nullptr;
    report(DescriptorBug, "File descriptor is closed more than once", Sym,
           Call.getOriginExpr(), Origin, "File descriptor first closed here",
           State, C);
    return;
  }

  State = State->add<QEMUClosedFDs>(Sym)->set<QEMUClosedFDOrigins>(
      Sym, Call.getOriginExpr());
  if (Binding)
    State = State->set<QEMUClosedFDBindings>(Sym, Binding)
                ->remove<QEMUReboundBindings>(Binding);
  C.addTransition(State);
}

bool QEMUResourceLifetimeChecker::checkClosedFDUses(const CallEvent &Call,
                                                    const FunctionDecl *FD,
                                                    CheckerContext &C) const {
  unsigned Mask = fdUseMask(FD->getName());
  if (!Mask)
    return false;
  ProgramStateRef State = C.getState();
  for (unsigned I = 0; I != Call.getNumArgs() && I != 8; ++I) {
    if (!(Mask & (1u << I)))
      continue;
    SymbolRef Sym = Call.getArgSVal(I).getAsSymbol();
    if (!Sym || !State->contains<QEMUClosedFDs>(Sym))
      continue;
    const MemRegion *Binding = State->get<QEMUClosedFDBindings>(Sym)
                                   ? *State->get<QEMUClosedFDBindings>(Sym)
                                   : nullptr;
    if (isReboundThrough(Binding, Call.getArgExpr(I), Sym, State, C))
      continue;
    const Expr *Origin = State->get<QEMUClosedFDOrigins>(Sym)
                             ? *State->get<QEMUClosedFDOrigins>(Sym)
                             : nullptr;
    report(
        DescriptorBug,
        ("Closed file descriptor is passed to '" + FD->getName() + "'").str(),
        Sym, Call.getArgExpr(I), Origin, "File descriptor closed here", State,
        C);
    return true;
  }
  return false;
}

void QEMUResourceLifetimeChecker::checkPreCall(const CallEvent &Call,
                                               CheckerContext &C) const {
  const FunctionDecl *FD = getCallee(Call);
  if (!FD)
    return;
  ClassifiedCall Classified = classifyCall(FD);

  if (Classified.Role == CallRole::GLibFree ||
      Classified.Role == CallRole::QAPIFree) {
    handlePointerRelease(Call, Classified, C);
    return;
  }

  ProgramStateRef State = C.getState();
  for (unsigned I = 0; I != Call.getNumArgs(); ++I) {
    SymbolRef Sym = Call.getArgSVal(I).getAsSymbol();
    if (!Sym)
      continue;
    if (reportReleasedPointerUse(
            Sym, Call.getArgExpr(I),
            ("Pointer is passed to '" + FD->getName() + "'").str(), State, C))
      return;
  }

  switch (Classified.Role) {
  case CallRole::QOMRef:
    handleRefChange(Call, RefKind::QOM, true, Classified.Indirect, C);
    return;
  case CallRole::QOMUnref:
    handleRefChange(Call, RefKind::QOM, false, Classified.Indirect, C);
    return;
  case CallRole::QObjectRef:
    handleRefChange(Call, RefKind::QObject, true, Classified.Indirect, C);
    return;
  case CallRole::QObjectUnref:
    handleRefChange(Call, RefKind::QObject, false, Classified.Indirect, C);
    return;
  case CallRole::FDClose:
    handleFDClose(Call, C);
    return;
  default:
    break;
  }

  checkClosedFDUses(Call, FD, C);
}

void QEMUResourceLifetimeChecker::checkPostCall(const CallEvent &Call,
                                                CheckerContext &C) const {
  const FunctionDecl *FD = getCallee(Call);
  if (!FD)
    return;
  std::optional<RefKind> Kind = constructorKind(FD);
  ClassifiedCall Classified = classifyCall(FD);
  if (!Kind && Classified.Role != CallRole::QOMRef)
    return;

  ProgramStateRef State = C.getState();
  SVal Return = Call.getReturnValue();
  SymbolRef ReturnSym = Return.getAsSymbol();
  if (!ReturnSym)
    return;

  if (Classified.Role == CallRole::QOMRef && Call.getNumArgs()) {
    SymbolRef ArgSym = Call.getArgSVal(0).getAsSymbol();
    if (ArgSym) {
      ArgSym = canonicalRef(State, ArgSym);
      if (getRefCount(State, RefKind::QOM, ArgSym)) {
        if (ReturnSym != ArgSym)
          State = State->set<QEMURefAliases>(ReturnSym, ArgSym);
        C.addTransition(State);
        return;
      }
    }
    Kind = RefKind::QOM;
  }

  auto [NonNull, Null] = assumeNonNull(State, Return);
  if (NonNull) {
    RefKind K = *Kind;
    NonNull = setRefCount(NonNull, K, ReturnSym, 1);
    C.addTransition(NonNull);
  }
  if (Null)
    C.addTransition(Null);
}

void QEMUResourceLifetimeChecker::checkLocation(SVal Loc, bool IsLoad,
                                                const Stmt *S,
                                                CheckerContext &C) const {
  SymbolRef Sym = Loc.getLocSymbolInBase();
  if (!Sym)
    return;
  ProgramStateRef State = C.getState();
  const Expr *At = dyn_cast_or_null<Expr>(S);
  const MemRegion *Binding = State->get<QEMUReleasedPointerBindings>(Sym)
                                 ? *State->get<QEMUReleasedPointerBindings>(Sym)
                                 : nullptr;
  const Expr *Origin = State->get<QEMUReleasedPointerOrigins>(Sym)
                           ? *State->get<QEMUReleasedPointerOrigins>(Sym)
                           : nullptr;

  if (State->get<QEMUReleasedPointers>(Sym) &&
      isLoopCarriedQueueRemoval(Binding, At, Origin, State, C)) {
    State = State->remove<QEMUReleasedPointers>(Sym)
                ->remove<QEMUReleasedPointerOrigins>(Sym)
                ->remove<QEMUReleasedPointerBindings>(Sym);
    if (Binding)
      State = State->remove<QEMUReboundBindings>(Binding);
    C.addTransition(State);
    return;
  }

  reportReleasedPointerUse(Sym, At, "Pointer is dereferenced", State, C);
}

void QEMUResourceLifetimeChecker::checkBind(SVal Loc, SVal Val, const Stmt *S,
                                            bool AtDeclInit,
                                            CheckerContext &C) const {
  const auto *VR = dyn_cast_or_null<VarRegion>(Loc.getAsRegion());
  ProgramStateRef State = C.getState();
  if (!VR || !VR->hasMemorySpace<StackSpaceRegion>(State) ||
      State->contains<QEMUReboundBindings>(VR))
    return;

  auto IsWatched = [&](const auto &Bindings) {
    for (auto [Sym, Binding] : Bindings)
      if (Binding == VR)
        return true;
    return false;
  };
  if (IsWatched(State->get<QEMUReleasedPointerBindings>()) ||
      IsWatched(State->get<QEMUReleasedRefBindings>()) ||
      IsWatched(State->get<QEMUClosedFDBindings>()))
    C.addTransition(State->add<QEMUReboundBindings>(VR));
}

void QEMUResourceLifetimeChecker::checkDeadSymbols(SymbolReaper &SymReaper,
                                                   CheckerContext &C) const {
  ProgramStateRef State = C.getState();
  ProgramStateRef Updated = State;

  for (auto [Sym, Kind] : State->get<QEMUReleasedPointers>()) {
    if (SymReaper.isDead(Sym)) {
      Updated = Updated->remove<QEMUReleasedPointers>(Sym);
      Updated = Updated->remove<QEMUReleasedPointerOrigins>(Sym);
      Updated = Updated->remove<QEMUReleasedPointerBindings>(Sym);
    }
  }
  for (SymbolRef Sym : State->get<QEMUClosedFDs>()) {
    if (SymReaper.isDead(Sym)) {
      Updated = Updated->remove<QEMUClosedFDs>(Sym);
      Updated = Updated->remove<QEMUClosedFDOrigins>(Sym);
      Updated = Updated->remove<QEMUClosedFDBindings>(Sym);
    }
  }

  auto HasLiveAlias = [&](SymbolRef Root) {
    for (auto [Alias, Parent] : State->get<QEMURefAliases>())
      if (canonicalRef(State, Parent) == Root && !SymReaper.isDead(Alias))
        return true;
    return false;
  };
  for (auto [Alias, Parent] : State->get<QEMURefAliases>())
    if (SymReaper.isDead(Alias))
      Updated = Updated->remove<QEMURefAliases>(Alias);

  auto RemoveDeadRef = [&](SymbolRef Sym) {
    if (!SymReaper.isDead(Sym) || HasLiveAlias(Sym))
      return;
    Updated = Updated->remove<QEMUQOMRefCounts>(Sym);
    Updated = Updated->remove<QEMUQObjectRefCounts>(Sym);
    Updated = Updated->remove<QEMUReleasedQOMRefs>(Sym);
    Updated = Updated->remove<QEMUReleasedQObjectRefs>(Sym);
    Updated = Updated->remove<QEMUReleasedRefOrigins>(Sym);
    Updated = Updated->remove<QEMUReleasedRefBindings>(Sym);
  };
  for (auto [Sym, Count] : State->get<QEMUQOMRefCounts>())
    RemoveDeadRef(Sym);
  for (auto [Sym, Count] : State->get<QEMUQObjectRefCounts>())
    RemoveDeadRef(Sym);
  for (SymbolRef Sym : State->get<QEMUReleasedQOMRefs>())
    RemoveDeadRef(Sym);
  for (SymbolRef Sym : State->get<QEMUReleasedQObjectRefs>())
    RemoveDeadRef(Sym);

  auto IsStillWatched = [&](const MemRegion *Binding) {
    for (auto [Sym, Watched] : Updated->get<QEMUReleasedPointerBindings>())
      if (Watched == Binding)
        return true;
    for (auto [Sym, Watched] : Updated->get<QEMUReleasedRefBindings>())
      if (Watched == Binding)
        return true;
    for (auto [Sym, Watched] : Updated->get<QEMUClosedFDBindings>())
      if (Watched == Binding)
        return true;
    return false;
  };
  for (const MemRegion *Binding : State->get<QEMUReboundBindings>())
    if (!IsStillWatched(Binding))
      Updated = Updated->remove<QEMUReboundBindings>(Binding);

  if (Updated != State)
    C.addTransition(Updated);
}

