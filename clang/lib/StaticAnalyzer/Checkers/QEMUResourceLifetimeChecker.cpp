// This checker models a deliberately small, high-confidence subset of QEMU's
// resource ownership conventions.  It diagnoses repeated GLib/QAPI frees,
// uses after those frees, repeated releases of locally-created QOM/QObject
// references, and repeated close/use of file descriptors.  It also follows
// the helper functions generated by GLib's automatic-cleanup macros.
//
// The checker does not report leaks and does not guess whether an unknown call
// transfers ownership.  Those restrictions are important for keeping the
// diagnostics useful on QEMU's large C API surface.
//
//===----------------------------------------------------------------------===//

