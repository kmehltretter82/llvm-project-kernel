static SVal releasedValue(const CallEvent &Call, ProgramStateRef State,
                          bool Indirect) {
  if (!Call.getNumArgs())
    return UnknownVal();
  SVal Value = Call.getArgSVal(0);
  if (!Indirect)
    return Value;
  const MemRegion *Region = Value.getAsRegion();
  return Region ? State->getSVal(Region) : UnknownVal();
}

static std::pair<ProgramStateRef, ProgramStateRef>
assumeNonNull(ProgramStateRef State, SVal Value) {
  std::optional<DefinedOrUnknownSVal> DV = Value.getAs<DefinedOrUnknownSVal>();
  if (!DV)
    return {State, nullptr};
  return State->assume(*DV);
}

