enum class CallRole : unsigned {
  None,
  GLibFree,
  QAPIFree,
  QOMRef,
  QOMUnref,
  QObjectRef,
  QObjectUnref,
  FDClose,
  TimerFree,
};

enum class RefKind : unsigned { QOM, QObject };

enum AsyncKind : unsigned {
  AsyncBottomHalf = 1u << 0,
  AsyncTimer = 1u << 1,
  AsyncBlockAIO = 1u << 2,
  AsyncCoroutine = 1u << 3,
  AsyncDeferredCall = 1u << 4,
  AsyncAIOHandler = 1u << 5,
  AsyncFDHandler = 1u << 6,
  AsyncNetwork = 1u << 7,
};

struct AsyncNetworkSend {
  unsigned SenderArgument;
  std::optional<unsigned> QueueArgument;
};

struct AsyncNetworkKey {
  const MemRegion *Sender = nullptr;
  const MemRegion *Queue = nullptr;
  bool DirectQueue = false;

  bool operator<(const AsyncNetworkKey &Other) const {
    if (DirectQueue != Other.DirectQueue)
      return DirectQueue < Other.DirectQueue;
    if (Queue != Other.Queue)
      return std::less<const MemRegion *>()(Queue, Other.Queue);
    return std::less<const MemRegion *>()(Sender, Other.Sender);
  }

  bool operator==(const AsyncNetworkKey &Other) const {
    return Sender == Other.Sender && Queue == Other.Queue &&
           DirectQueue == Other.DirectQueue;
  }

  void Profile(llvm::FoldingSetNodeID &ID) const {
    ID.AddPointer(Sender);
    ID.AddPointer(Queue);
    ID.AddBoolean(DirectQueue);
  }
};

struct AsyncRegistration {
  unsigned Kind;
  unsigned OpaqueArgument;
  std::optional<unsigned> HandleArgument;
  bool ReturnHandle;
  bool StartsPending;
};

struct AsyncFDKey {
  SymbolRef Symbol = nullptr;
  int64_t Concrete = 0;

  bool operator<(const AsyncFDKey &Other) const {
    if (Symbol != Other.Symbol)
      return std::less<SymbolRef>()(Symbol, Other.Symbol);
    return Concrete < Other.Concrete;
  }

  bool operator==(const AsyncFDKey &Other) const {
    return Symbol == Other.Symbol && Concrete == Other.Concrete;
  }

  void Profile(llvm::FoldingSetNodeID &ID) const {
    ID.AddPointer(Symbol);
    ID.AddInteger(Concrete);
  }
};

struct ClassifiedCall {
  CallRole Role = CallRole::None;
  bool Indirect = false;
};

static const FunctionDecl *getCallee(const CallEvent &Call) {
  const auto *FD = dyn_cast_or_null<FunctionDecl>(Call.getDecl());
  if (!FD || !FD->getIdentifier() || !FD->getDeclContext()->isFileContext())
    return nullptr;
  return FD;
}

static bool hasAnnotation(const FunctionDecl *FD, StringRef Annotation) {
  if (!FD)
    return false;
  for (const FunctionDecl *Redecl : FD->getCanonicalDecl()->redecls())
    for (const auto *A : Redecl->specific_attrs<AnnotateAttr>())
      if (A->getAnnotation() == Annotation)
        return true;
  return false;
}

static CallRole classifyDirectTarget(const FunctionDecl *FD) {
  if (!FD || !FD->getIdentifier())
    return CallRole::None;

  if (hasAnnotation(FD, "qemu::releases_glib"))
    return CallRole::GLibFree;
  if (hasAnnotation(FD, "qemu::releases_qapi"))
    return CallRole::QAPIFree;
  if (hasAnnotation(FD, "qemu::refs_qom"))
    return CallRole::QOMRef;
  if (hasAnnotation(FD, "qemu::unrefs_qom"))
    return CallRole::QOMUnref;
  if (hasAnnotation(FD, "qemu::refs_qobject"))
    return CallRole::QObjectRef;
  if (hasAnnotation(FD, "qemu::unrefs_qobject"))
    return CallRole::QObjectUnref;
  if (hasAnnotation(FD, "qemu::closes_fd"))
    return CallRole::FDClose;

  StringRef Name = FD->getName();
  if (Name == "g_free")
    return CallRole::GLibFree;
  if (Name.starts_with("qapi_free_"))
    return CallRole::QAPIFree;
  if (Name == "object_ref")
    return CallRole::QOMRef;
  if (Name == "object_unref")
    return CallRole::QOMUnref;
  if (Name == "qobject_ref_impl")
    return CallRole::QObjectRef;
  if (Name == "qobject_unref_impl" || Name == "qdict_unref" ||
      Name == "qlist_unref" || Name == "qstring_unref" ||
      Name == "qnum_unref" || Name == "qbool_unref" || Name == "qnull_unref")
    return CallRole::QObjectUnref;
  if (Name == "close" || Name == "qemu_close" || Name == "closesocket" ||
      Name == "qemu_close_wrap" || Name == "qemu_close_socket_osfhandle")
    return CallRole::FDClose;
  if (Name == "timer_free")
    return CallRole::TimerFree;
  return CallRole::None;
}

static bool isReleaseRole(CallRole Role) {
  return Role == CallRole::GLibFree || Role == CallRole::QAPIFree ||
         Role == CallRole::QOMUnref || Role == CallRole::QObjectUnref ||
         Role == CallRole::TimerFree;
}

static CallRole
findCleanupTarget(const Stmt *S, unsigned Depth,
                  llvm::SmallPtrSetImpl<const FunctionDecl *> &Seen) {
  if (!S || Depth > 16)
    return CallRole::None;

  if (const auto *CE = dyn_cast<CallExpr>(S)) {
    if (const FunctionDecl *Target = CE->getDirectCallee()) {
      CallRole Role = classifyDirectTarget(Target);
      if (isReleaseRole(Role))
        return Role;

      StringRef Name = Target->getName();
      if ((Name.starts_with("glib_autoptr_clear_") ||
           Name.starts_with("glib_autoptr_cleanup_")) &&
          Seen.insert(Target->getCanonicalDecl()).second) {
        if (CallRole Nested =
                findCleanupTarget(Target->getBody(), Depth + 1, Seen);
            Nested != CallRole::None)
          return Nested;
      }
    }
  }

  for (const Stmt *Child : S->children())
    if (CallRole Role = findCleanupTarget(Child, Depth, Seen);
        Role != CallRole::None)
      return Role;
  return CallRole::None;
}

static ClassifiedCall classifyCall(const FunctionDecl *FD) {
  CallRole Direct = classifyDirectTarget(FD);
  if (Direct != CallRole::None)
    return {Direct, false};

  StringRef Name = FD->getName();
  if (Name == "g_autoptr_cleanup_generic_gfree")
    return {CallRole::GLibFree, true};
  if (!Name.starts_with("glib_autoptr_cleanup_"))
    return {};

  llvm::SmallPtrSet<const FunctionDecl *, 8> Seen;
  Seen.insert(FD->getCanonicalDecl());
  return {findCleanupTarget(FD->getBody(), 0, Seen), true};
}

static std::optional<RefKind> constructorKind(const FunctionDecl *FD) {
  if (!FD || !FD->getIdentifier())
    return std::nullopt;
  if (hasAnnotation(FD, "qemu::returns_owned_qom"))
    return RefKind::QOM;
  if (hasAnnotation(FD, "qemu::returns_owned_qobject"))
    return RefKind::QObject;

  StringRef Name = FD->getName();
  if (Name == "object_new" || Name == "object_new_with_class" ||
      Name == "object_new_with_props" || Name == "object_new_with_propv" ||
      Name == "object_new_with_props_from_qdict" ||
      Name == "object_new_with_props_parentless" ||
      Name == "object_new_with_propv_parentless" ||
      Name == "object_new_with_props_from_qdict_parentless")
    return RefKind::QOM;

  if (Name == "qdict_new" || Name == "qlist_new" || Name == "qstring_new" ||
      Name.starts_with("qstring_from_") || Name.starts_with("qnum_from_") ||
      Name == "qbool_from_bool" || Name == "qnull" ||
      Name.starts_with("qobject_from_"))
    return RefKind::QObject;
  return std::nullopt;
}

static unsigned fdUseMask(StringRef Name) {
  return llvm::StringSwitch<unsigned>(Name)
      .Cases({"read", "write", "pread", "pwrite", "readv", "writev"}, 1u)
      .Cases({"recv", "send", "recvfrom", "sendto", "recvmsg", "sendmsg"}, 1u)
      .Cases({"ioctl", "fcntl", "fstat", "fsync", "fdatasync", "lseek"}, 1u)
      .Cases({"accept", "accept4", "bind", "connect", "listen", "shutdown"}, 1u)
      .Cases({"getsockname", "getpeername", "getsockopt", "setsockopt"}, 1u)
      .Cases({"dup", "fdopen", "qemu_set_nonblock", "qemu_set_block",
              "qemu_set_cloexec", "qemu_lock_fd", "qemu_unlock_fd"},
             1u)
      .Cases({"qemu_read_full", "qemu_write_full", "qemu_recv", "qemu_send",
              "qemu_accept", "socket_set_fast_reuse", "socket_set_nodelay",
              "socket_set_cork"},
             1u)
      .Case("dup2", 1u)
      .Case("dup3", 1u)
      .Case("sendfile", 3u)
      .Default(0u);
}

static std::optional<AsyncRegistration>
classifyAsyncRegistration(const FunctionDecl *FD, unsigned NumArgs) {
  if (!FD || !FD->getIdentifier())
    return std::nullopt;
  StringRef Name = FD->getName();

  if (Name == "qemu_bh_new_full" && NumArgs >= 2)
    return AsyncRegistration{AsyncBottomHalf, 1, std::nullopt, true, false};
  if (Name == "aio_bh_new_full" && NumArgs >= 3)
    return AsyncRegistration{AsyncBottomHalf, 2, std::nullopt, true, false};

  if (Name == "timer_new_full" && NumArgs >= 6)
    return AsyncRegistration{AsyncTimer, 5, std::nullopt, true, false};
  if (Name == "timer_new" && NumArgs >= 4)
    return AsyncRegistration{AsyncTimer, 3, std::nullopt, true, false};
  if ((Name == "timer_new_ns" || Name == "timer_new_us" ||
       Name == "timer_new_ms") &&
      NumArgs >= 3)
    return AsyncRegistration{AsyncTimer, 2, std::nullopt, true, false};
  if (Name == "aio_timer_new_with_attrs" && NumArgs >= 6)
    return AsyncRegistration{AsyncTimer, 5, std::nullopt, true, false};
  if (Name == "aio_timer_new" && NumArgs >= 5)
    return AsyncRegistration{AsyncTimer, 4, std::nullopt, true, false};

  if (Name == "timer_init_full" && NumArgs >= 7)
    return AsyncRegistration{AsyncTimer, 6, 0, false, false};
  if (Name == "timer_init" && NumArgs >= 5)
    return AsyncRegistration{AsyncTimer, 4, 0, false, false};
  if ((Name == "timer_init_ns" || Name == "timer_init_us" ||
       Name == "timer_init_ms") &&
      NumArgs >= 4)
    return AsyncRegistration{AsyncTimer, 3, 0, false, false};
  if (Name == "aio_timer_init_with_attrs" && NumArgs >= 7)
    return AsyncRegistration{AsyncTimer, 6, 1, false, false};
  if (Name == "aio_timer_init" && NumArgs >= 6)
    return AsyncRegistration{AsyncTimer, 5, 1, false, false};

  if (Name == "qemu_coroutine_create" && NumArgs >= 2)
    return AsyncRegistration{AsyncCoroutine, 1, std::nullopt, true, false};

  if ((Name == "blk_aio_pwrite_zeroes" || Name == "blk_aio_preadv" ||
       Name == "blk_aio_pwritev" || Name == "blk_aio_zone_report" ||
       Name == "blk_aio_zone_mgmt" || Name == "blk_aio_zone_append") &&
      NumArgs >= 6)
    return AsyncRegistration{AsyncBlockAIO, 5, std::nullopt, true, true};
  if (Name == "blk_aio_flush" && NumArgs >= 3)
    return AsyncRegistration{AsyncBlockAIO, 2, std::nullopt, true, true};
  if ((Name == "blk_aio_pdiscard" || Name == "blk_aio_ioctl") && NumArgs >= 5)
    return AsyncRegistration{AsyncBlockAIO, 4, std::nullopt, true, true};

  return std::nullopt;
}

static bool isNamedRecordPointer(QualType Type, StringRef Name) {
  if (Type.isNull() || !Type->isPointerType())
    return false;
  const RecordDecl *Record =
      Type->getPointeeType().getUnqualifiedType()->getAsRecordDecl();
  return Record && Record->getName() == Name;
}

static bool isExactBuiltinType(QualType Type, QualType Expected) {
  return !Type.isNull() && Type.getCanonicalType().getUnqualifiedType() ==
                               Expected.getCanonicalType().getUnqualifiedType();
}

static bool isSSizeType(QualType Type, ASTContext &Context) {
  return !Type.isNull() && Type->isSignedIntegerType() &&
         Context.getTypeSize(Type) ==
             Context.getTypeSize(Context.getSizeType());
}

static bool isBytePointer(QualType Type, ASTContext &Context) {
  if (Type.isNull() || !Type->isPointerType())
    return false;
  QualType Pointee = Type->getPointeeType().getUnqualifiedType();
  return isExactBuiltinType(Pointee, Context.UnsignedCharTy);
}

static bool isNetPacketSentPointer(QualType Type, ASTContext &Context) {
  if (Type.isNull() || !Type->isPointerType())
    return false;
  const auto *Prototype = Type->getPointeeType()->getAs<FunctionProtoType>();
  return Prototype && !Prototype->isVariadic() &&
         Prototype->getReturnType()->isVoidType() &&
         Prototype->getNumParams() == 2 &&
         isNamedRecordPointer(Prototype->getParamType(0), "NetClientState") &&
         isSSizeType(Prototype->getParamType(1), Context);
}

static std::optional<AsyncNetworkSend>
classifyAsyncNetworkSend(const FunctionDecl *FD, unsigned NumArgs) {
  if (!FD || !FD->getIdentifier() || FD->isVariadic() ||
      FD->getNumParams() != NumArgs ||
      !isSSizeType(FD->getReturnType(), FD->getASTContext()))
    return std::nullopt;

  StringRef Name = FD->getName();
  ASTContext &Context = FD->getASTContext();
  auto Parameter = [&](unsigned Index) {
    return FD->getParamDecl(Index)->getType();
  };
  if (Name == "qemu_send_packet_async" || Name == "qemu_sendv_packet_async") {
    if (NumArgs != 4 || !isNamedRecordPointer(Parameter(0), "NetClientState") ||
        !isExactBuiltinType(Parameter(2), Context.IntTy) ||
        !isNetPacketSentPointer(Parameter(3), Context))
      return std::nullopt;
    if (Name == "qemu_send_packet_async") {
      if (!isBytePointer(Parameter(1), Context))
        return std::nullopt;
    } else if (!isNamedRecordPointer(Parameter(1), "iovec")) {
      return std::nullopt;
    }
    return AsyncNetworkSend{0, std::nullopt};
  }
  if (Name == "qemu_net_queue_send" || Name == "qemu_net_queue_send_iov") {
    if (NumArgs != 6 || !isNamedRecordPointer(Parameter(0), "NetQueue") ||
        !isNamedRecordPointer(Parameter(1), "NetClientState") ||
        !isExactBuiltinType(Parameter(2), Context.UnsignedIntTy) ||
        !isNetPacketSentPointer(Parameter(5), Context))
      return std::nullopt;
    if (Name == "qemu_net_queue_send") {
      if (!isBytePointer(Parameter(3), Context) ||
          !isExactBuiltinType(Parameter(4), Context.getSizeType()))
        return std::nullopt;
    } else if (!isNamedRecordPointer(Parameter(3), "iovec") ||
               !isExactBuiltinType(Parameter(4), Context.IntTy)) {
      return std::nullopt;
    }
    return AsyncNetworkSend{1, 0};
  }
  return std::nullopt;
}

