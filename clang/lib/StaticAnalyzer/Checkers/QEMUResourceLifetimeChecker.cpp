static bool referencesLocalBinding(const Stmt *S, const MemRegion *Binding,
                                   ProgramStateRef State, CheckerContext &C) {
  if (!S || !Binding)
    return false;
  if (const auto *DRE = dyn_cast<DeclRefExpr>(S)) {
    const auto *VD = dyn_cast<VarDecl>(DRE->getDecl());
    if (VD && State->getRegion(VD, C.getStackFrame()) == Binding)
      return true;
  }
  for (const Stmt *Child : S->children())
    if (referencesLocalBinding(Child, Binding, State, C))
      return true;
  return false;
}

static const Stmt *getLoopBody(const Stmt *S) {
  if (const auto *Loop = dyn_cast<ForStmt>(S))
    return Loop->getBody();
  if (const auto *Loop = dyn_cast<WhileStmt>(S))
    return Loop->getBody();
  if (const auto *Loop = dyn_cast<DoStmt>(S))
    return Loop->getBody();
  if (const auto *Loop = dyn_cast<CXXForRangeStmt>(S))
    return Loop->getBody();
  return nullptr;
}

static const Stmt *findEnclosingBodyLoop(DynTypedNode Node, ASTContext &Ctx) {
  const Stmt *Child = Node.get<Stmt>();
  for (;;) {
    DynTypedNodeList Parents = Ctx.getParents(Node);
    if (Parents.size() != 1)
      return nullptr;
    Node = Parents[0];
    const Stmt *Parent = Node.get<Stmt>();
    if (!Parent)
      return nullptr;
    if (const Stmt *Body = getLoopBody(Parent))
      return Body == Child ? Parent : nullptr;
    Child = Parent;
  }
}

static bool containsQueueRemoval(const Stmt *S, const MemRegion *Binding,
                                 SourceLocation ReleaseLoc,
                                 ProgramStateRef State, CheckerContext &C) {
  if (!S)
    return false;

  if (const auto *E = dyn_cast<Expr>(S)) {
    const SourceManager &SM = C.getSourceManager();
    SourceLocation RemovalLoc = SM.getExpansionLoc(E->getExprLoc());
    if (isQEMUQueueRemovalMacro(E, C) &&
        referencesLocalBinding(E, Binding, State, C) && RemovalLoc.isValid() &&
        ReleaseLoc.isValid() &&
        SM.getFileID(RemovalLoc) == SM.getFileID(ReleaseLoc) &&
        SM.isBeforeInTranslationUnit(RemovalLoc, ReleaseLoc))
      return true;
  }

  for (const Stmt *Child : S->children())
    if (containsQueueRemoval(Child, Binding, ReleaseLoc, State, C))
      return true;
  return false;
}

static bool hasPriorTopLevelQueueRemoval(const Stmt *LoopBody,
                                         const MemRegion *Binding,
                                         SourceLocation ReleaseLoc,
                                         ProgramStateRef State,
                                         CheckerContext &C) {
  const auto *Body = dyn_cast_or_null<CompoundStmt>(LoopBody);
  if (!Body)
    return false;

  // Queue-removal macros expand to a top-level do/while statement in QEMU.
  // Requiring that shape avoids treating a conditional removal as proof that
  // every path reaching the later release unlinked the element.
  for (const Stmt *Child : Body->body())
    if (isa<DoStmt>(Child) &&
        containsQueueRemoval(Child, Binding, ReleaseLoc, State, C))
      return true;
  return false;
}

